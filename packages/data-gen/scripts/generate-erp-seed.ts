// ---------------------------------------------------------------------------
// Manifest
// ---------------------------------------------------------------------------
const counts = Object.fromEntries(
  Object.entries(data).filter(([, value]) => Array.isArray(value)).map(([key, value]) => [key, (value as unknown[]).length]),
);
const checksum = createHash("sha256").update(JSON.stringify(data)).digest("hex");
const manifest = {
  generatedBy: "packages/data-gen/scripts/generate-erp-seed.ts",
  provenance: "illustrative",
  seed: COMPANY_MANIFEST.seed,
  organization: data.organizationSlug,
  checksum,
  config: ERP_DEMO_CONFIG,
  scenarios: ERP_SCENARIOS,
  counts,
  files: ["supabase/seed/0008_erp_reference.sql", "supabase/seed/0009_erp_people.sql", "supabase/seed/0010_erp_care.sql"],
};

writeFileSync(resolve(seedDir, "0008_erp_reference.sql"), reference.join("\n"));
writeFileSync(resolve(seedDir, "0009_erp_people.sql"), people.join("\n"));
writeFileSync(resolve(seedDir, "0010_erp_care.sql"), care.join("\n"));
mkdirSync(snapshotDir, { recursive: true });
writeFileSync(resolve(snapshotDir, "erp-manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
console.log(`ERP seed written: ${JSON.stringify(counts)}; checksum ${checksum.slice(0, 12)}…`);
