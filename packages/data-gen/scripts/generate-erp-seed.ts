/**
 * Writes the hospital-operations (ERP) seed for the demo organization:
 *
 *   supabase/seed/0008_erp_reference.sql  settings, departments, specialties,
 *                                          shift patterns, service catalogue,
 *                                          where each service is offered
 *   supabase/seed/0009_erp_people.sql     staff, doctors, consultation slots,
 *                                          rosters, in/out punches
 *   supabase/seed/0010_erp_care.sql       patients, visits, services delivered
 *   data/snapshots/erp-manifest.json      counts, scenarios, configuration, checksum
 *
 * Run: npm run generate:erp --workspace=@orbit/data-gen
 *
 * Deterministic (same output every run) and idempotent (`on conflict do
 * nothing`; visits are inserted in their final state, then their services,
 * which the triggers check against each visit's window). Facility and organization
 * ids are resolved from slugs inside the SQL, never hard-coded. Applying the
 * seed re-checks every row against the database's own integrity triggers.
 *
 * No operator accounts or memberships are written here: those are provisioned
 * out of band (scripts/provision-erp-accounts.ts, ADR 0013 §2).
 */
import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { ERP_DEMO_CONFIG, ERP_SCENARIOS, generateErpDataset } from "../src/erp.ts";
import { COMPANY_MANIFEST } from "../src/manifest.ts";

const here = dirname(fileURLToPath(import.meta.url));
const seedDir = resolve(here, "../../../supabase/seed");
const snapshotDir = resolve(here, "../../../data/snapshots");

const data = generateErpDataset();
const ORG = `(select id from orbit.organizations where slug = ${q(data.organizationSlug)})`;

function q(value: string): string {
  return `'${value.replaceAll("'", "''")}'`;
}

function v(value: string | number | boolean | null): string {
  if (value === null) return "null";
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  return q(value);
}

/** Splits rows into batches so no single statement is enormous. */
function batches<T>(rows: readonly T[], size = 1000): T[][] {
  const out: T[][] = [];
  for (let i = 0; i < rows.length; i += size) out.push(rows.slice(i, i + size));
  return out;
}

function valuesInsert<T>(
  rows: readonly T[],
  columns: string,
  toValues: (row: T) => readonly (string | number | boolean | null)[],
  statement: (values: string) => string,
): string[] {
  return batches(rows).map((batch) =>
    statement(`(values\n${batch.map((row) => `  (${toValues(row).map(v).join(", ")})`).join(",\n")}\n) as v(${columns})`),
  );
}

function header(title: string): string[] {
  return [
    `-- GENERATED by packages/data-gen/scripts/generate-erp-seed.ts. Do not edit by hand.`,
    `-- ${title}`,
    `-- Fictional demonstration records (ADR 0016). Illustrative; not clinical or employment data.`,
    `-- Idempotent. Requires migration 20261001000100_orbit_erp_operations.sql and seed 0001.`,
    "",
    "begin;",
    "",
  ];
}

