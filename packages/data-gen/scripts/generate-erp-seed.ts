const s = ERP_DEMO_CONFIG.settings;
const reference = [
  ...header("Reference data: settings, departments, specialties, shift patterns, services."),
  `insert into orbit_erp.erp_settings (organization_id, late_grace_minutes, early_exit_grace_minutes,
  punch_window_before_minutes, punch_window_after_minutes, credential_warning_days)
select ${ORG}, ${s.lateGraceMinutes}, ${s.earlyExitGraceMinutes}, ${s.punchWindowBeforeMinutes}, ${s.punchWindowAfterMinutes}, ${s.credentialWarningDays}
on conflict (organization_id) do nothing;`,
  ...valuesInsert(data.departments, "id, code, name", (d) => [d.id, d.code, d.name], (values) =>
    `insert into orbit_erp.departments (id, organization_id, code, name)
select v.id::uuid, ${ORG}, v.code, v.name from ${values}
on conflict (id) do nothing;`),
  ...valuesInsert(data.specialties, "id, code, name", (d) => [d.id, d.code, d.name], (values) =>
    `insert into orbit_erp.specialties (id, organization_id, code, name)
select v.id::uuid, ${ORG}, v.code, v.name from ${values}
on conflict (id) do nothing;`),
  ...valuesInsert(data.shifts, "id, code, name, start_time, end_time, break_minutes", (t) => [t.id, t.code, t.name, t.start, t.end, t.breakMinutes], (values) =>
    `insert into orbit_erp.shift_templates (id, organization_id, code, name, start_time, end_time, break_minutes)
select v.id::uuid, ${ORG}, v.code, v.name, v.start_time::time, v.end_time::time, v.break_minutes from ${values}
on conflict (id) do nothing;`),
  ...valuesInsert(data.services, "id, code, name, category, department_code, unit", (x) => [x.id, x.code, x.name, x.category, x.departmentCode, x.unit], (values) =>
    `insert into orbit_erp.services (id, organization_id, service_code, name, category, department_id, unit)
select v.id::uuid, d.organization_id, v.code, v.name, v.category, d.id, v.unit
from ${values}
join orbit_erp.departments d on d.organization_id = ${ORG} and d.code = v.department_code
on conflict (id) do nothing;`),
  ...valuesInsert(data.availability, "facility_slug, service_id", (a) => [a.facility, a.serviceId], (values) =>
    `insert into orbit_erp.facility_services (organization_id, facility_id, service_id, is_available)
select f.organization_id, f.id, v.service_id::uuid, true
from ${values}
join orbit.facilities f on f.organization_id = ${ORG} and f.slug = v.facility_slug
on conflict (facility_id, service_id) do nothing;`),
  "",
  "commit;",
  "",
];

