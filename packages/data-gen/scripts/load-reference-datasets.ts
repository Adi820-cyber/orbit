/**
 * Builds the SQL that loads the two reference hospital datasets into Orbit
 * (ADR 0020). See src/reference.ts for what is kept, dropped and summarised.
 *
 * The source datasets are outside material and stay out of Git
 * (docs/source-material/README.md). Extract the two archives first:
 *
 *   DataSets/extracted/hospital/   the CSVs of hospital_synthetic_shalaka/hospital_data
 *   DataSets/extracted/clinic/     the CSVs of archive.zip
 *
 * Run: npm run load:reference --workspace=@orbit/data-gen
 *      (REFERENCE_DATASETS_DIR overrides DataSets/extracted)
 *
 * Writes, all git-ignored because they hold records derived from the source:
 *   supabase/seed/local/reference/0201_catalogue.sql   departments, specialties, services, where offered
 *   supabase/seed/local/reference/0202_people.sql      staff and doctors
 *   supabase/seed/local/reference/0203_patients.sql    patients (fictional name, sex, birth year)
 *   supabase/seed/local/reference/0204_visits.sql      visits
 *   supabase/seed/local/reference/0205_services.sql    services delivered
 *   supabase/seed/local/reference/0206_knowledge.sql   chatbot knowledge (summaries only)
 *   supabase/seed/local/reference/0207_prices.sql      service prices derived from the dataset (ADR 0022)
 * and, committed, counts only:
 *   data/snapshots/reference-manifest.json
 *
 * Deterministic and idempotent (`on conflict do nothing`; knowledge is upserted).
 * Every row is still checked by the database's own triggers when applied.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { stableUuid } from "../src/erp.ts";
import {
  buildReference,
  checksumOf,
  derivePrices,
  CLINIC_TABLES,
  HOSPITAL_TABLES,
  NEW_DEPARTMENTS,
  NEW_SERVICES,
  NEW_SPECIALTIES,
  parseCsv,
  type ClinicTables,
  type HospitalTables,
  type Table,
} from "../src/reference.ts";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../../..");
const sourceDir = resolve(process.env.REFERENCE_DATASETS_DIR ?? resolve(root, "DataSets/extracted"));
const outDir = resolve(root, "supabase/seed/local/reference");
const snapshotDir = resolve(root, "data/snapshots");

function readTables<T extends readonly string[]>(dir: string, names: T): Record<T[number], Table> {
  const out = {} as Record<T[number], Table>;
  for (const name of names) {
    const file = resolve(dir, `${name}.csv`);
    if (!existsSync(file)) throw new Error(`missing ${file}: extract the reference datasets first (see this script's header)`);
    out[name as T[number]] = parseCsv(readFileSync(file, "utf8"));
  }
  return out;
}

const hospital = readTables(resolve(sourceDir, "hospital"), HOSPITAL_TABLES) as HospitalTables;
const clinic = readTables(resolve(sourceDir, "clinic"), CLINIC_TABLES) as ClinicTables;
const result = buildReference(hospital, clinic);

// ---------------------------------------------------------------------------
// SQL helpers (same conventions as generate-erp-seed.ts)
// ---------------------------------------------------------------------------
const ORG = "(select id from orbit.organizations where slug = 'kestrion')";
const q = (value: string) => `'${value.replaceAll("'", "''")}'`;
const v = (value: string | number | boolean | null) =>
  value === null ? "null" : typeof value === "number" || typeof value === "boolean" ? String(value) : q(value);

function batches<T>(rows: readonly T[], size = 1000): T[][] {
  const out: T[][] = [];
  for (let i = 0; i < rows.length; i += size) out.push(rows.slice(i, i + size));
  return out;
}

function valuesInsert<T>(
  rows: readonly T[],
  columns: string,
  toValues: (row: T) => readonly (string | number | boolean | null)[],
  statement: (values: string) => string,
): string[] {
  return batches(rows).map((batch) =>
    statement(`(values\n${batch.map((row) => `  (${toValues(row).map(v).join(", ")})`).join(",\n")}\n) as v(${columns})`),
  );
}

const header = (title: string) => [
  "-- GENERATED by packages/data-gen/scripts/load-reference-datasets.ts. Do not edit; do not commit.",
  `-- ${title}`,
  "-- Derived from outside synthetic datasets (ADR 0020). Illustrative; not real hospital data.",
  "",
  "begin;",
  "",
];
const footer = ["", "commit;", ""];
const dept = (code: string) => stableUuid("department", code);

// ---------------------------------------------------------------------------
// Files
// ---------------------------------------------------------------------------
const catalogue = [
  ...header("New departments, specialties and services, and where each service is offered."),
  ...valuesInsert(NEW_DEPARTMENTS, "id, code, name", ([c, n]) => [dept(c), c, n], (values) =>
    `insert into orbit_erp.departments (id, organization_id, code, name)
select v.id::uuid, ${ORG}, v.code, v.name from ${values}
on conflict do nothing;`),
  ...valuesInsert(NEW_SPECIALTIES, "id, code, name", ([c, n]) => [stableUuid("specialty", c), c, n], (values) =>
    `insert into orbit_erp.specialties (id, organization_id, code, name)
select v.id::uuid, ${ORG}, v.code, v.name from ${values}
on conflict do nothing;`),
  ...valuesInsert(NEW_SERVICES, "id, code, name, category, department_code, unit", ([c, n, cat, d, u]) => [stableUuid("service", c), c, n, cat, d, u], (values) =>
    `insert into orbit_erp.services (id, organization_id, service_code, name, category, department_id, unit)
select v.id::uuid, d.organization_id, v.code, v.name, v.category, d.id, v.unit
from ${values}
join orbit_erp.departments d on d.organization_id = ${ORG} and d.code = v.department_code
on conflict do nothing;`),
  ...valuesInsert(result.availability, "facility_slug, service_code", (a) => [a.facility, a.serviceCode], (values) =>
    `insert into orbit_erp.facility_services (organization_id, facility_id, service_id, is_available)
select f.organization_id, f.id, s.id, true
from ${values}
join orbit.facilities f on f.organization_id = ${ORG} and f.slug = v.facility_slug
join orbit_erp.services s on s.organization_id = f.organization_id and s.service_code = v.service_code
on conflict (facility_id, service_id) do nothing;`),
  ...footer,
];

const people = [
  ...header("Staff and doctors (fictional names; no contact details)."),
  ...valuesInsert(
    result.staff,
    "id, facility_slug, department_id, employee_code, display_name, staff_type, designation, joined_on, is_critical_role",
    (s) => [s.id, s.facility, dept(s.departmentCode), s.employeeCode, s.displayName, s.staffType, s.designation, s.joinedOn, s.isCriticalRole],
    (values) => `insert into orbit_erp.staff (id, organization_id, facility_id, department_id, employee_code, display_name,
  staff_type, designation, employment_status, joined_on, is_critical_role)
select v.id::uuid, f.organization_id, f.id, v.department_id::uuid, v.employee_code, v.display_name,
  v.staff_type, v.designation, 'active', v.joined_on::date, v.is_critical_role
from ${values}
join orbit.facilities f on f.organization_id = ${ORG} and f.slug = v.facility_slug
on conflict do nothing;`,
  ),
  ...valuesInsert(
    result.doctors,
    "staff_id, specialty_id, registration_number, credential_expires_on, employment_type",
    (d) => [d.staffId, stableUuid("specialty", d.specialtyCode), d.registrationNumber, d.credentialExpiresOn, d.employmentType],
    (values) => `insert into orbit_erp.doctor_profiles (staff_id, organization_id, specialty_id, registration_number,
  credential_expires_on, employment_type)
select v.staff_id::uuid, ${ORG}, v.specialty_id::uuid, v.registration_number, v.credential_expires_on::date, v.employment_type
from ${values}
on conflict do nothing;`,
  ),
  ...footer,
];

const patients = [
  ...header("Patients: a fictional name, sex and birth year only."),
  ...valuesInsert(
    result.patients,
    "id, facility_slug, mrn, display_name, sex, birth_year, created_at",
    (p) => [p.id, p.facility, p.mrn, p.displayName, p.sex, p.birthYear, p.createdAt],
    (values) => `insert into orbit_erp.patients (id, organization_id, home_facility_id, mrn, display_name, sex, birth_year,
  created_by_membership_id, created_at, updated_at)
select v.id::uuid, f.organization_id, f.id, v.mrn, v.display_name, v.sex, v.birth_year, null,
  v.created_at::timestamptz, v.created_at::timestamptz
from ${values}
join orbit.facilities f on f.organization_id = ${ORG} and f.slug = v.facility_slug
on conflict do nothing;`,
  ),
  ...footer,
];

const visits = [
  ...header("Visits: hospital stays and outpatient appointments."),
  ...valuesInsert(
    result.encounters,
    "id, patient_id, facility_slug, department_id, doctor_id, encounter_type, status, started_at, ended_at",
    (e) => [e.id, e.patientId, e.facility, dept(e.departmentCode), e.doctorId, e.type, e.status, e.startedAt, e.endedAt],
    (values) => `insert into orbit_erp.encounters (id, organization_id, patient_id, facility_id, department_id,
  attending_doctor_id, encounter_type, status, started_at, ended_at, created_by_membership_id, created_at, updated_at)
select v.id::uuid, f.organization_id, v.patient_id::uuid, f.id, v.department_id::uuid,
  v.doctor_id::uuid, v.encounter_type, v.status, v.started_at::timestamptz, v.ended_at::timestamptz, null,
  v.started_at::timestamptz, v.ended_at::timestamptz
from ${values}
join orbit.facilities f on f.organization_id = ${ORG} and f.slug = v.facility_slug
on conflict do nothing;`,
  ),
  ...footer,
];

const services = [
  ...header("Services delivered: bed-days, diagnostic tests, procedures and clinic treatments."),
  ...valuesInsert(
    result.deliveries,
    "encounter_id, service_code, performer_id, quantity, performed_at, idempotency_key",
    (d) => [d.encounterId, d.serviceCode, d.performerId, d.quantity, d.performedAt, d.key],
    (values) => `insert into orbit_erp.service_deliveries (organization_id, encounter_id, facility_id, service_id,
  performed_by_staff_id, quantity, performed_at, status, idempotency_key, recorded_by_membership_id, created_at, updated_at)
select e.organization_id, e.id, e.facility_id, s.id, v.performer_id::uuid, v.quantity,
  v.performed_at::timestamptz, 'completed', v.idempotency_key::uuid, null, v.performed_at::timestamptz, v.performed_at::timestamptz
from ${values}
join orbit_erp.encounters e on e.id = v.encounter_id::uuid
join orbit_erp.services s on s.organization_id = e.organization_id and s.service_code = v.service_code
on conflict (organization_id, idempotency_key) do nothing;`,
  ),
  ...footer,
];

const knowledge = [
  ...header("Chatbot knowledge: exact summaries of the reference datasets, scoped by role and entity."),
  ...valuesInsert(
    result.chunks,
    "source_key, source, domain, roles, grain, facility_slug, title, content",
    (c) => [c.key, c.source, c.domain, `{${c.roles.join(",")}}`, c.grain, c.facility, c.title, c.content],
    (values) => `insert into orbit.knowledge_chunks as k
  (organization_id, source_key, source, domain, visible_roles, entity_grain, entity_id, title, content, content_hash)
select o.id, v.source_key, v.source, v.domain,
  case when v.roles = '{}' then (select array_agg(r.role_id order by r.role_id) from orbit.role_ids r) else v.roles::text[] end,
  v.grain,
  case v.grain when 'group' then o.id
               when 'facility' then (select f.id from orbit.facilities f where f.organization_id = o.id and f.slug = v.facility_slug) end,
  v.title, v.content, md5(v.title || E'\\n' || v.content)
from ${values}
cross join orbit.organizations o
where o.slug = 'kestrion'
on conflict (organization_id, source_key) where source_key is not null
do update set source = excluded.source, domain = excluded.domain, visible_roles = excluded.visible_roles,
  entity_grain = excluded.entity_grain, entity_id = excluded.entity_id, title = excluded.title,
  content = excluded.content, content_hash = excluded.content_hash, updated_at = now()
where k.content_hash is distinct from excluded.content_hash;`,
  ),
  ...footer,
];

// Prices: the dataset's own amounts (derivePrices). Each hospital's price list
// is filled only where no price is set yet, so an admin's price is never
// overwritten. Run as the database owner: the admin-only price rule binds the
// API's role (migration 20261006000200).
const derivedPrices = derivePrices(hospital);
const prices = [
  ...header("Service prices in rupees, derived from the reference hospital dataset (ADR 0022)."),
  ...valuesInsert(
    derivedPrices,
    "service_code, price",
    (p) => [p.serviceCode, p.price],
    (values) => `update orbit_erp.facility_services fs
   set illustrative_tariff = v.price::numeric, version = fs.version + 1, updated_at = now()
  from ${values}
  join orbit_erp.services s on s.service_code = v.service_code
  join orbit.organizations o on o.id = s.organization_id and o.slug = 'kestrion'
 where fs.service_id = s.id
   and fs.illustrative_tariff is null;`,
  ),
  ...footer,
];
result.manifest.counts["pricedServices"] = derivedPrices.length;

mkdirSync(outDir, { recursive: true });
const files: [string, string[]][] = [
  ["0201_catalogue.sql", catalogue],
  ["0202_people.sql", people],
  ["0203_patients.sql", patients],
  ["0204_visits.sql", visits],
  ["0205_services.sql", services],
  ["0206_knowledge.sql", knowledge],
  ["0207_prices.sql", prices],
];
for (const [name, lines] of files) writeFileSync(resolve(outDir, name), lines.join("\n"));

mkdirSync(snapshotDir, { recursive: true });
writeFileSync(
  resolve(snapshotDir, "reference-manifest.json"),
  `${JSON.stringify({ generatedBy: "packages/data-gen/scripts/load-reference-datasets.ts", provenance: "illustrative", checksum: checksumOf(result), ...result.manifest }, null, 2)}\n`,
);

